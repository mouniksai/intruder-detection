"""
scripts/run_all_architectures.py
================================
Unified Benchmark Orchestrator for Review 2 Deep Learning Architecture Suite.

Runs and benchmarks all 5 architectures independently:
1. AlexNet (2012)
2. VGG-16 (2014)
3. GoogLeNet / Inception-v1 (2014)
4. ResNet-50 (2015)
5. MobileNetV2 (2018)

Produces a comparative cross-model evaluation matrix covering:
- Parameters (Millions) & Model Footprint (FP32 MB)
- Closed-Set Multi-Class Accuracy, Precision, Recall, F1
- Open-Set Rejection Rate, False Accept Rate (FAR), False Reject Rate (FRR)
- Equal Error Rate (EER) & ROC-AUC
- Per-Frame Inference Latency (ms) & Deployment Suitability
"""

import os
import sys
import argparse
from pathlib import Path
import pandas as pd
from tabulate import tabulate

WORKSPACE_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(WORKSPACE_ROOT))

from scripts.run_alexnet import run_alexnet
from scripts.run_vgg16 import run_vgg16
from scripts.run_googlenet import run_googlenet
from scripts.run_resnet50 import run_resnet50
from scripts.run_mobilenetv2 import run_mobilenetv2


def main():
    parser = argparse.ArgumentParser(description="Benchmark Review 2 Deep Learning Architectures")
    parser.add_argument("--epochs", type=int, default=12, help="Epochs per architecture")
    parser.add_argument("--batch-size", type=int, default=16, help="Batch size")
    parser.add_argument("--device", type=str, default="cpu", help="Device (cpu or cuda)")
    parser.add_argument("--test-only", action="store_true", help="Evaluate existing checkpoints without retraining")
    parser.add_argument("--models", nargs="+", default=["alexnet", "vgg16", "googlenet", "resnet50", "mobilenetv2"],
                        help="Subset of models to run")
    args = parser.parse_args()

    print("=" * 90)
    print("   REVIEW 2 DEEP LEARNING BENCHMARK: 5-ARCHITECTURE SUITE")
    print("=" * 90)

    model_runners = {
        "alexnet": ("AlexNet (2012)", run_alexnet),
        "vgg16": ("VGG-16 (2014)", run_vgg16),
        "googlenet": ("GoogLeNet / Inception-v1 (2014)", run_googlenet),
        "resnet50": ("ResNet-50 (2015)", run_resnet50),
        "mobilenetv2": ("MobileNetV2 (2018)", run_mobilenetv2),
    }

    all_results = []

    for model_key in args.models:
        if model_key not in model_runners:
            print(f"[!] Warning: Unknown model key '{model_key}', skipping.")
            continue

        name, runner_fn = model_runners[model_key]
        print(f"\n>>> Running independent evaluation for: {name} ...\n")
        try:
            res = runner_fn(
                epochs=args.epochs,
                batch_size=args.batch_size,
                device_name=args.device,
                test_only=args.test_only
            )
            all_results.append(res)
        except Exception as e:
            print(f"[!] Error running {name}: {e}")
            import traceback
            traceback.print_exc()

    if not all_results:
        print("[!] No benchmark results collected.")
        return

    # Create Comparison DataFrame
    df = pd.DataFrame(all_results)
    
    # Format table for clean display
    display_df = pd.DataFrame({
        "Architecture": df["architecture"],
        "Params (M)": df["parameters_m"].apply(lambda x: f"{x:.2f}M"),
        "Size (MB)": df["model_size_mb"].apply(lambda x: f"{x:.1f} MB"),
        "Test Acc": df["test_acc"].apply(lambda x: f"{x*100:.1f}%"),
        "Precision": df["precision"].apply(lambda x: f"{x:.3f}"),
        "Recall": df["recall"].apply(lambda x: f"{x:.3f}"),
        "F1-Score": df["f1_score"].apply(lambda x: f"{x:.3f}"),
        "ROC-AUC": df["roc_auc"].apply(lambda x: f"{x:.3f}"),
        "EER": df["eer"].apply(lambda x: f"{x*100:.1f}%"),
        "Rejection Rate": df["rejection_rate"].apply(lambda x: f"{x*100:.1f}%"),
        "FAR": df["far"].apply(lambda x: f"{x*100:.1f}%"),
        "FRR": df["frr"].apply(lambda x: f"{x*100:.1f}%"),
        "Latency": df["latency_ms"].apply(lambda x: f"{x:.2f} ms")
    })

    print("\n" + "=" * 90)
    print("               FINAL REVIEW 2 DEEP LEARNING COMPARATIVE MATRIX")
    print("=" * 90)
    print(tabulate(display_df, headers="keys", tablefmt="github", showindex=False))
    print("=" * 90)

    # Save summary markdown table
    summary_md_path = os.path.join(WORKSPACE_ROOT, "reports", "BENCHMARK_REVIEW_2_SUMMARY.md")
    with open(summary_md_path, "w") as f:
        f.write("# Review 2 Deep Learning Architecture Benchmark Summary\n\n")
        f.write(tabulate(display_df, headers="keys", tablefmt="github", showindex=False))
        f.write("\n\n*Generated by `scripts/run_all_architectures.py`*\n")

    print(f"[*] Benchmark summary saved to: {summary_md_path}")

    # Save JSON summary for automated plotting and reports
    import json
    json_path = os.path.join(WORKSPACE_ROOT, "reports", "metrics_summary.json")
    with open(json_path, "w") as f:
        json.dump(all_results, f, indent=2)
    print(f"[*] Raw metrics JSON saved to: {json_path}")


if __name__ == "__main__":
    main()
